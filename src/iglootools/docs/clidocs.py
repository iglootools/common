"""A Markdown reference for a Typer command line, made by `typer ... utils docs`."""

import subprocess
import sys
from collections.abc import Callable, Sequence
from enum import StrEnum

# The header nbkp's and photree's references already carry; changing it rewrites them.
HEADER = "<!-- AUTO-GENERATED by: mise run clidocs — do not edit manually -->"

type Run = Callable[[Sequence[str]], subprocess.CompletedProcess[str]]


class ClidocsErrorKind(StrEnum):
    """Why the CLI reference could not be generated."""

    TYPER_DOCS_FAILED = "typer-docs-failed"


class ClidocsError(RuntimeError):
    """The CLI reference could not be generated: the kind, and typer's message."""

    def __init__(self, kind: ClidocsErrorKind, detail: str) -> None:
        """Build the error from its kind and typer's message."""
        super().__init__(f"{kind}: {detail}")
        self.kind = kind
        self.detail = detail


def typer_docs_command(
    module: str,
    name: str,
    python: str = sys.executable,
) -> list[str]:
    """
    Return the command that prints *module*'s Typer app as Markdown, titled *name*.

    Run it in the project's environment, where *module* is importable.
    """
    return [python, "-m", "typer", module, "utils", "docs", "--name", name]


def generate(command: Sequence[str], run: Run | None = None) -> str:
    """
    Return the reference file's full content: the header, then typer's Markdown.

    Raises ClidocsError(TYPER_DOCS_FAILED) when *command* fails.
    """
    result = (run or _run)(command)
    if result.returncode != 0:
        raise ClidocsError(ClidocsErrorKind.TYPER_DOCS_FAILED, result.stderr)
    return f"{HEADER}\n\n{result.stdout.rstrip(chr(10))}\n"


def _run(command: Sequence[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(command, check=False, capture_output=True, text=True)
