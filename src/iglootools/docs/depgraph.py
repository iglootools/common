"""A mermaid graph of the dependencies between a package's top-level modules.

pydeps analyses the imports and prints graphviz DOT; this turns that into a mermaid
`graph TD` and splices it into the architecture document between two markers, or renders
it as ASCII.
"""

import re
import shutil
import subprocess
import sys
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from enum import StrEnum
from importlib.metadata import packages_distributions
from importlib.util import find_spec
from pathlib import Path
from textwrap import indent

from mermaid_ascii import parse_mermaid, render_ascii

# The marker text and the section's wording are what nbkp's and photree's architecture
# documents already carry; changing them rewrites every consumer's generated section.
BEGIN_MARKER = (
    "<!-- BEGIN MODULE OVERVIEW "
    "(auto-generated by: mise run depgraph — do not edit manually) -->"
)
END_MARKER = "<!-- END MODULE OVERVIEW -->"
_MERMAID_INDENT = "    "

type Run = Callable[[Sequence[str]], subprocess.CompletedProcess[str]]


class DepgraphErrorKind(StrEnum):
    GRAPHVIZ_MISSING = "graphviz-missing"
    PACKAGE_NOT_FOUND = "package-not-found"
    PYDEPS_FAILED = "pydeps-failed"
    MARKERS_MISSING = "markers-missing"


class DepgraphError(RuntimeError):
    def __init__(self, kind: DepgraphErrorKind, detail: str = "") -> None:
        super().__init__(f"{kind}: {detail}".rstrip(": "))
        self.kind = kind
        self.detail = detail


@dataclass(frozen=True)
class Graph:
    nodes: tuple[str, ...]
    """Module labels, relative to the package."""
    edges: tuple[tuple[str, str], ...]
    """(dependent, dependency) pairs."""


def third_party_imports(
    requirements: Sequence[str],
    distributions: Mapping[str, list[str]] | None = None,
) -> list[str]:
    """Import names provided by the distributions *requirements* name.

    *distributions* maps import names to distribution names, as
    importlib.metadata.packages_distributions() does for the running environment.
    """
    available = packages_distributions() if distributions is None else distributions
    declared = {
        _canonical(re.split(r"[\s<>=!~;\[(@]", r, maxsplit=1)[0]) for r in requirements
    }
    return sorted(
        module
        for module, dists in available.items()
        if any(_canonical(dist) in declared for dist in dists)
    )


def _canonical(distribution: str) -> str:
    return re.sub(r"[-_.]+", "-", distribution).lower()


def package_directory(package: str) -> Path:
    """Where *package* is imported from in the running environment."""
    spec = find_spec(package)
    if spec is None or not spec.submodule_search_locations:
        raise DepgraphError(DepgraphErrorKind.PACKAGE_NOT_FOUND, package)
    return Path(next(iter(spec.submodule_search_locations)))


def pydeps_command(
    package_dir: Path, excludes: Sequence[str], python: str = sys.executable
) -> list[str]:
    package = package_dir.name
    return [
        python,
        "-m",
        "pydeps",
        str(package_dir),
        "--show-dot",
        "--no-output",
        "--no-show",
        "--max-module-depth",
        "2",
        "--only",
        package,
        "--rmprefix",
        f"{package}.",
        # --only filters what pydeps prints, not what it traverses: without the
        # third-party exclusions it follows every import into them, which is most of its
        # run time. The graph is unchanged.
        *(["--exclude", *excludes] if excludes else []),
    ]


def run_pydeps(
    command: Sequence[str],
    run: Run | None = None,
    which: Callable[[str], str | None] = shutil.which,
) -> str:
    """pydeps' DOT output. pydeps renders through graphviz's `dot`, so check for it."""
    if which("dot") is None:
        raise DepgraphError(DepgraphErrorKind.GRAPHVIZ_MISSING)
    result = (run or _run)(command)
    if result.returncode != 0:
        raise DepgraphError(DepgraphErrorKind.PYDEPS_FAILED, result.stderr)
    return result.stdout


def _run(command: Sequence[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(command, check=False, capture_output=True, text=True)


def parse_dot(dot: str) -> Graph:
    """pydeps draws an edge from a dependency to its dependent; Graph reverses it."""
    node_pattern = re.compile(r'^\s+(\w+)\s+\[.*?label="([^"]+)".*?\]', re.MULTILINE)
    labels = {m.group(1): m.group(2) for m in node_pattern.finditer(dot)}
    edge_pattern = re.compile(r"^\s+(\w+)\s+->\s+(\w+)", re.MULTILINE)
    return Graph(
        nodes=tuple(labels[node_id] for node_id in sorted(labels)),
        edges=tuple(
            sorted(
                (labels.get(dependent, dependent), labels.get(dep, dep))
                for dep, dependent in (m.groups() for m in edge_pattern.finditer(dot))
            )
        ),
    )


def to_mermaid(graph: Graph, is_package: Callable[[str], bool]) -> str:
    """Sorted, so regenerating is deterministic, which --check relies on."""
    node_lines = [
        f'{label}["{label}/"]' if is_package(label) else f'{label}["{label}"]'
        for label in graph.nodes
    ]
    edge_lines = [f"{src} --> {dst}" for src, dst in graph.edges]
    return "\n".join(
        [
            "graph TD",
            *(indent(line, _MERMAID_INDENT) for line in node_lines),
            "",
            *(indent(line, _MERMAID_INDENT) for line in edge_lines),
        ]
    )


def to_ascii(mermaid: str) -> str:
    return render_ascii(parse_mermaid(mermaid))


def module_overview(mermaid: str) -> str:
    return (
        f"{BEGIN_MARKER}\n"
        "## Module Overview\n"
        "\n"
        "Dependencies between top-level modules "
        "(auto-generated via `mise run depgraph`):\n"
        "```mermaid\n"
        f"{mermaid}\n"
        "```\n"
        f"{END_MARKER}"
    )


def splice(document: str, section: str) -> str:
    """Replace everything from BEGIN_MARKER to END_MARKER with *section*."""
    begin = document.find(BEGIN_MARKER)
    end = document.find(END_MARKER)
    if begin == -1 or end == -1:
        raise DepgraphError(DepgraphErrorKind.MARKERS_MISSING)
    return document[:begin] + section + document[end + len(END_MARKER) :]
